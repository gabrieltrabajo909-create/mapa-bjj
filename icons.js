function iconoSVG(id, size = 64) {
  const ic = ICONOS[id];
  if (!ic) return '';
  const parts = ic.f.map(s => {
    const c = s[1] === 'g' ? '#3a4150' : COL[s[1]];
    if (s[0] === 'c') return `<circle cx="${s[2]}" cy="${s[3]}" r="5" fill="${c}"/>`;
    if (s[0] === 'l') return `<polyline points="${s.slice(2).join(' ')}" fill="none" stroke="${c}" stroke-width="${s[1] === 'g' ? 2 : 4.5}" stroke-linecap="round" stroke-linejoin="round"/>`;
    if (s[0] === 'p') return `<path d="${s[2]}" fill="none" stroke="${c}" stroke-width="4" stroke-linecap="round" ${s[3] ? 'marker-end="url(#flechaIc)"' : ''}/>`;
  }).join('');
  return `<svg viewBox="0 0 64 64" width="${size}" height="${size}" xmlns="http://www.w3.org/2000/svg">${parts}</svg>`;
}
